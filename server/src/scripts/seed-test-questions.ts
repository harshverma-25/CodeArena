async function seedTestQuestions() {
  const uri = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/codearena';
  console.log('🚀 Connecting to MongoDB for initial test question bank seeding...');
  await mongoose.connect(uri);
  console.log('✅ Connected to MongoDB.');

  try {
    // 1. Resolve existing Categories and Subjects
    const categories = await CategoryModel.find({}).lean();
    const subjects = await SubjectModel.find({}).lean();

    const catMapBySlug = new Map<string, any>();
    for (const c of categories) {
      catMapBySlug.set(c.slug, c);
    }

    const subjMapBySlug = new Map<string, any>();
    for (const s of subjects) {
      subjMapBySlug.set(s.slug, s);
    }

    // 2. Validate that all required categories and subjects exist
    console.log(`Checking category and subject records in DB...`);
    const missingSubjects: string[] = [];
    for (const q of TEST_QUESTION_BANK) {
      if (!catMapBySlug.has(q.categorySlug)) {
        throw new Error(`Category slug '${q.categorySlug}' not found in database!`);
      }
      if (!subjMapBySlug.has(q.subjectSlug)) {
        if (!missingSubjects.includes(q.subjectSlug)) {
          missingSubjects.push(q.subjectSlug);
        }
      }
    }

    if (missingSubjects.length > 0) {
      throw new Error(`The following required subjects are missing from the database: ${missingSubjects.join(', ')}`);
    }

    console.log(`✅ All 19 target subjects successfully verified in DB.`);

    // 3. Upsert questions idempotently
    let insertedCount = 0;
    let updatedCount = 0;
    let skippedCount = 0;

    const subjectTallies = new Map<string, number>();

    for (const qDef of TEST_QUESTION_BANK) {
      const catDoc = catMapBySlug.get(qDef.categorySlug)!;
      const subjDoc = subjMapBySlug.get(qDef.subjectSlug)!;

      const existing = await QuestionModel.findOne({ questionId: qDef.questionId });

      const questionData = {
        questionId: qDef.questionId,
        categoryId: catDoc._id,
        subjectId: subjDoc._id,
        topic: qDef.subjectSlug, // legacy compatibility field
        difficulty: qDef.difficulty,
        question: qDef.question,
        options: qDef.options,
        correctAnswer: qDef.correctAnswer,
        explanation: qDef.explanation,
        isPublished: true,
      };

      if (!existing) {
        await QuestionModel.create(questionData);
        insertedCount++;
      } else {
        await QuestionModel.updateOne({ questionId: qDef.questionId }, { $set: questionData });
        updatedCount++;
      }

      subjectTallies.set(qDef.subjectSlug, (subjectTallies.get(qDef.subjectSlug) || 0) + 1);
    }

    console.log('\n==================================================');
    console.log('🎉 TEST QUESTION SEEDING COMPLETED!');
    console.log('==================================================');
    console.log(`Total questions processed : ${TEST_QUESTION_BANK.length}`);
    console.log(`Newly inserted            : ${insertedCount}`);
    console.log(`Updated / verified        : ${updatedCount}`);
    console.log(`Skipped                   : ${skippedCount}`);

    console.log('\n📊 Questions Per Subject (Target: exactly 10 each):');
    for (const [slug, count] of subjectTallies.entries()) {
      const sDoc = subjMapBySlug.get(slug);
      console.log(`  - [${slug}] ${sDoc?.name}: ${count} questions`);
    }

    // 4. Verify Final Database Counts
    console.log('\n🔍 Verifying Final Published Question Counts in Database:');
    let totalVerified = 0;
    for (const cat of categories) {
      const catSubjects = subjects.filter((s) => s.categoryId.toString() === cat._id.toString());
      let catTotal = 0;
      console.log(`\nCategory: ${cat.name} (${cat.slug})`);
      for (const subj of catSubjects) {
        const count = await QuestionModel.countDocuments({ subjectId: subj._id, isPublished: true });
        catTotal += count;
        totalVerified += count;
        console.log(`  * ${subj.name} (${subj.slug}): ${count} published (>= 10: ${count >= 10 ? '✅' : '❌'})`);
      }
      console.log(`  └─ Total published in ${cat.name}: ${catTotal}`);
    }

    console.log(`\nTotal published questions across all categories: ${totalVerified}`);
  } catch (err) {
    console.error('❌ Seeding failed:', err);
    process.exit(1);
  } finally {
    await mongoose.disconnect();
    console.log('🔌 Disconnected from MongoDB.');
  }
}

seedTestQuestions().catch(console.error);
